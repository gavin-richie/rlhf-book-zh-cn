import re

def convert(text):
    # Sort by length descending so longer matches replace first
    sorted_items = sorted(tr_to_simp.items(), key=lambda kv: len(kv[0]), reverse=True)
    result = text
    for tr, simp in sorted_items:
        result = result.replace(tr, simp)
    return result

dir_path = 'public/assets/widgets-zh-cn'
for fname in sorted(os.listdir(dir_path)):
    if not fname.endswith('.js'):
        continue
    fpath = os.path.join(dir_path, fname)
    orig = open(fpath, 'r', encoding='utf-8').read()
    converted = convert(orig)
    if converted != orig:
        changed = sum(1 for a, b in zip(orig, converted) if a != b)
        print(f'{fname}: {changed} chars changed')
        open(fpath, 'w', encoding='utf-8').write(converted)
    else:
        # Check for any remaining traditional chars
        remaining = []
        for tr in tr_to_simp.keys():
            if tr in orig:
                remaining.append(tr)
        if remaining:
            print(f'{fname}: still has {remaining}')
        else:
            print(f'{fname}: OK')
