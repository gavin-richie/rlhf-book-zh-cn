def apply_replacements(text):
    """Apply terminology replacements in order (longest patterns first)."""
    # Sort by length descending so longer patterns match first
    sorted_replacements = sorted(REPLACEMENTS, key=lambda x: len(x[0]), reverse=True)

    for tw, cn in sorted_replacements:
        text = text.replace(tw, cn)

    return text


def extract_and_translate_md(content):
    """Extract markdown content, translate it, and put it back."""
    pattern = r'(<script type="text/markdown" id="chapter-md">)(.*?)(</script>)'
    match = re.search(pattern, content, re.DOTALL)
    if not match:
        return content

    before = match.group(1)
    markdown = match.group(2)
    after = match.group(3)

    # Apply replacements to markdown content
    translated_md = apply_replacements(markdown)

    return f"{before}{translated_md}{after}"


def process_html_file(src_path, dst_path):
    """Process a single HTML file."""
    content = src_path.read_text(encoding='utf-8')

    # Translate markdown content
    content = extract_and_translate_md(content)

    # Translate HTML body text (titles, labels, etc.)
    # Replace zh-Hant with zh-Hans in lang attribute
    content = content.replace('lang="zh-Hant"', 'lang="zh-Hans"')

    # Apply replacements to the rest of the HTML
    content = apply_replacements(content)

    dst_path.write_text(content, encoding='utf-8')
    print(f"  OK {dst_path.name}")


from pathlib import Path
import re

def main():
    # List all HTML files in source directory
    html_files = sorted([f for f in SRC_DIR.iterdir() if f.suffix == '.html'])

    print("Translating all chapter files...")
    for src_path in html_files:
        dst_path = DST_DIR / src_path.name
        process_html_file(src_path, dst_path)

    print(f"\nDone. Translated {len(html_files)} files.")


if __name__ == "__main__":
    main()
