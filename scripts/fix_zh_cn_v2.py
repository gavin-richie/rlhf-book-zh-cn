def apply_terms(text):
    sorted_terms = sorted(TW_TO_CN, key=lambda x: len(x[0]), reverse=True)
    for tw, cn in sorted_terms:
        text = text.replace(tw, cn)
    return text


def process_file(filename):
    src = os.path.join(SRC_DIR, filename)
    dst = os.path.join(DST_DIR, filename)

    with open(src, 'r', encoding='utf-8') as f:
        content = f.read()

    original = content
    content = apply_terms(content)

    if content != original:
        with open(dst, 'w', encoding='utf-8') as f:
            f.write(content)
        print(f"  OK  {filename}")
        return True
    else:
        print(f"  -   {filename} (no changes)")
        return False


def main():
    files = [f for f in os.listdir(SRC_DIR) if f.endswith('.html')]
    files.sort()

    print("Applying Taiwan→Mainland terminology...")
    changed = 0
    for f in files:
        if process_file(f):
            changed += 1

    print(f"\nDone. {changed}/{len(files)} files updated.")


if __name__ == "__main__":
    main()
