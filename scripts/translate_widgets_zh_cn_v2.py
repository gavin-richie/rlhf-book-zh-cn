def convert_text(text):
    """Apply Traditional→Simplified conversion with domain-specific terminology."""
    # Sort by length descending so longer matches replace first
    sorted_items = sorted(TR_TO_SIMP.items(), key=lambda kv: len(kv[0]), reverse=True)
    result = text
    for tr, simp in sorted_items:
        result = result.replace(tr, simp)
    return result

# Also handle some context-specific replacements that need string-literal awareness
def post_process(text):
    """Apply context-aware replacements after basic conversion."""
    # The generic '資料' → '数据' is mostly fine, but in some contexts like '資料來源'
    # we already handled it above. The script handles it correctly via longest-match-first.
    return text

def main():
    src_dir = r'E:\Disk\Work\CodeBase\WebStormProjects\rlhf-book\public\assets\widgets'
    dst_dir = r'E:\Disk\Work\CodeBase\WebStormProjects\rlhf-book\public\assets\widgets-zh-cn'

    # Get list of files to translate
    files = sorted([f for f in os.listdir(src_dir) if f.endswith('.js')])
    print(f"Translating {len(files)} files...")

    for fname in files:
        src_path = os.path.join(src_dir, fname)
        dst_path = os.path.join(dst_dir, fname)

        with open(src_path, 'r', encoding='utf-8') as f:
            content = f.read()

        translated = convert_text(content)
        translated = post_process(translated)

        with open(dst_path, 'w', encoding='utf-8') as f:
            f.write(translated)

        # Count changed characters
        changed = sum(1 for a, b in zip(content, translated) if a != b)
        print(f"  {fname}: {changed} chars changed")

    print("Done!")

if __name__ == '__main__':
    main()
