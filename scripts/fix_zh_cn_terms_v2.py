def apply_terms(text):
    sorted_terms = sorted(TERMS, key=lambda x: len(x[0]), reverse=True)
    for tw, cn in sorted_terms:
        text = text.replace(tw, cn)
    return text

def main():
    files = ['ch01.html', 'ch02.html', 'ch03.html', 'ch04.html',
             'ch05.html', 'ch06.html', 'ch07.html', 'ch08.html',
             'ch09.html', 'ch10.html', 'ch11.html', 'ch12.html',
             'ch13.html', 'ch14.html', 'ch15.html', 'ch16.html',
             'ch17.html', 'appa.html', 'appb.html', 'appc.html',
             'bibliography.html']

    print("Fixing Taiwan terminology in zh-cn files...")
    for fname in files:
        dst = os.path.join(SRC_DIR, fname)
        if not os.path.exists(dst):
            continue

        with open(dst, 'r', encoding='utf-8') as f:
            content = f.read()

        original = content
        content = apply_terms(content)

        if content != original:
            with open(dst, 'w', encoding='utf-8') as f:
                f.write(content)
            print(f"  OK  {fname}")
        else:
            print(f"  -   {fname} (no changes)")

    print("\nDone.")

if __name__ == "__main__":
    main()
