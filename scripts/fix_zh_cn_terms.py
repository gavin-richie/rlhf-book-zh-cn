def apply_terms(text):
    """Apply terminology replacements."""
    sorted_terms = sorted(TERMS, key=lambda x: len(x[0]), reverse=True)
    for tw, cn in sorted_terms:
        text = text.replace(tw, cn)
    return text


def process_file(filename):
    src = os.path.join(DST_DIR, filename)
    if not os.path.exists(src):
        print(f"  SKIP {filename} (not found)")
        return False

    with open(src, 'r', encoding='utf-8') as f:
        content = f.read()

    original = content
    content = apply_terms(content)

    if content != original:
        with open(src, 'w', encoding='utf-8') as f:
            f.write(content)
        print(f"  OK  {filename}")
        return True
    else:
        print(f"  -   {filename} (no changes)")
        return False


def main():
    files = []
    for f in os.listdir(DST_DIR):
        if f.endswith('.html'):
            files.append(f)
    files.sort()

    print("Applying Taiwan→Mainland terminology fixes...")
    changed = 0
    for f in files:
        if process_file(f):
            changed += 1

    print(f"\nDone. {changed}/{len(files)} files updated.")


if __name__ == "__main__":
    main()
