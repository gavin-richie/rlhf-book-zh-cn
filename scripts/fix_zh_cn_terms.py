def apply_terms(text):
    for tw, cn in TERMS:
        text = text.replace(tw, cn)
    return text


def process_file(filepath):
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    original = content
    content = apply_terms(content)

    if content != original:
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(content)
        return True
    return False


def main():
    # Process chapter files
    print("Processing chapter files...")
    chapter_count = 0
    for f in sorted(DST_DIR.glob('*.html')):
        if process_file(f):
            print(f"  OK  {f.name}")
            chapter_count += 1

    # Process widget files
    print("Processing widget files...")
    widget_count = 0
    for f in sorted(WIDGET_DIR.glob('*.js')):
        if process_file(f):
            print(f"  OK  {f.name}")
            widget_count += 1

    print(f"\nDone. {chapter_count} chapters + {widget_count} widgets updated.")


if __name__ == "__main__":
    main()