def apply_terms(text):
    sorted_terms = sorted(TERMS, key=lambda x: len(x[0]), reverse=True)
    for tw, cn in sorted_terms:
        text = text.replace(tw, cn)
    return text


def process_file(filename):
    src = os.path.join(SRC_DIR, filename)
    dst = os.path.join(DST_DIR, filename)

    with open(src, 'r', encoding='utf-8') as f:
        content = f.read()

    # Step 1: OpenCC t2s (繁转简)
    content = cc.convert(content)

    # Step 2: Terminology replacements
    content = apply_terms(content)

    # Step 3: Update HTML lang
    content = content.replace('lang="zh-Hant"', 'lang="zh-Hans"')

    with open(dst, 'w', encoding='utf-8') as f:
        f.write(content)

    print(f"  OK  {filename}")


def main():
    files = []
    for f in os.listdir(SRC_DIR):
        if f.endswith('.html'):
            files.append(f)
    files.sort()

    print("Translating all chapter files...")
    for f in files:
        process_file(f)

    print(f"\nDone. {len(files)} files translated.")


if __name__ == "__main__":
    main()
