# Sort by length descending so longer phrases are matched first
TERM_MAP.sort(key=lambda x: -len(x[0]))

def convert_text(text):
    # First pass: zhconv for basic character conversion
    result = zhconv.convert(text, "zh-hans")
    # Second pass: domain-specific terminology
    for trad, simp in TERM_MAP:
        result = result.replace(trad, simp)
    return result

for f in files:
    path = os.path.join(base, f)
    if not os.path.exists(path):
        print(f"SKIP (missing): {f}")
        continue
    with open(path, "r", encoding="utf-8") as fh:
        content = fh.read()

    m = re.search(r'(<script[^>]*id="chapter-md"[^>]*>)(.*?)(</script>)', content, re.DOTALL)
    if not m:
        print(f"SKIP (no chapter-md): {f}")
        continue

    before = content[:m.start()]
    tag_open = m.group(1)
    md_content = m.group(2)
    tag_close = m.group(3)
    after = content[m.end():]

    converted = convert_text(md_content)
    new_content = before + tag_open + converted + tag_close + after

    with open(path, "w", encoding="utf-8") as fh:
        fh.write(new_content)
    print(f"OK: {f}")

print("\nDone!")
